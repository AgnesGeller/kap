export function getHungarianCityFromPostalCode(postalCode: string) {
  const code = postalCode.replace(/\D/g, "").slice(0, 4);

  if (code.length !== 4) {
    return "";
  }

  if (exactPostalCodes[code]) {
    return exactPostalCodes[code];
  }

  if (code.startsWith("1")) {
    return "Budapest";
  }

  return "";
}
